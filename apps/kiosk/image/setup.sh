#!/bin/sh
# Runs chrooted inside the image after the base system, the extra packages and
# the `skel` tree are in place (alpine-make-vm-image --script-chroot), so every
# path below is an image path.
#
# The build tool bind-mounts this script's directory at /mnt, so the options the
# TUI selected arrive in /mnt/build.env as plain KEY=value lines — written by
# apps/kiosk/image/build.ts. Every setting that used to be hardcoded here is now
# read from that file; the defaults reproduce the old image exactly.
set -eu

ENV_FILE=/mnt/build.env

read_env() {
    # Prints the value for a key, or nothing when the file or key is absent so an
    # old build directory still produces a working image.
    sed -n "s/^$1=//p" "$ENV_FILE" 2>/dev/null || true
}

hostname_value=$(read_env HOSTNAME)
timezone_value=$(read_env TIMEZONE)
kiosk_url=$(read_env KIOSK_URL)
orientation=$(read_env ORIENTATION)
output_mode=$(read_env OUTPUT_MODE)
output_scale=$(read_env OUTPUT_SCALE)

: "${hostname_value:=kiosk}"
: "${timezone_value:=Europe/Budapest}"
: "${kiosk_url:=https://kiosk.filc.petrik.hu}"

# The browser session runs as an unprivileged user. seatd admits members of the
# `seat` group to the seat cage needs; the others cover direct device access.
adduser -D -u 1000 -h /home/kiosk -s /bin/sh kiosk
for group in seat video input; do
    addgroup kiosk "$group"
done

# Boot order: udev/seatd provide the seat, chronyd fixes the clock (a box that
# just came back from a power cut must not show yesterday's timetable), then
# kanshi applies the output transform before cage claims the outputs, and kiosk
# starts the browser.
rc-update add seatd default
rc-update add chronyd default
rc-update add kiosk default

# kanshi only exists when the TUI asked for display config, and the service file
# is generated by build.ts (Alpine ships no init script for it). It enforces the
# orientation, mode and scale against whatever output the box actually has,
# because cage has no flag for any of them.
if [ -f /etc/init.d/kanshi ]; then
    rc-update add kanshi default
    chmod 0755 /etc/init.d/kanshi
else
    if [ -n "$orientation" ] && [ "$orientation" != normal ]; then
        echo 'setup.sh: a transform was selected but no kanshi service exists' >&2
        exit 1
    fi
fi

printf '%s\n' "$hostname_value" > /etc/hostname

# Times on the kiosk pages are local time; the image has no interactive setup.
ln -sf "/usr/share/zoneinfo/$timezone_value" /etc/localtime
printf '%s\n' "$timezone_value" > /etc/timezone

# The SPA origin the box loads. Written rather than kept as a skel file so the
# TUI's answer and the running box cannot drift apart.
printf '%s\n' "$kiosk_url" > /etc/kiosk/url

# Display configuration, mirrored into the image so it is visible on a box that
# has not booted yet. kanshi's own config is generated by build.ts.
if [ -n "$orientation" ] || [ -n "$output_mode" ] || [ -n "$output_scale" ]; then
    {
        printf 'orientation=%s\n' "${orientation:-normal}"
        printf 'mode=%s\n' "${output_mode:-none}"
        printf 'scale=%s\n' "${output_scale:-1}"
    } > /etc/kiosk/display
fi

# DHCP has to write the resolver config, and the rootfs is read-only: point it
# at tmpfs so busybox's udhcpc script can replace it on every boot.
ln -sf /run/resolv.conf /etc/resolv.conf

# Mountpoint for skel/etc/kiosk/fstab.tmpfs: busybox seedrng writes its seed
# there and fails the boot with a read-only root.
install -d -m 0700 /var/lib/seedrng

# alpine-make-vm-image generated /etc/fstab with the root entry (filesystem UUID
# + fs type) this image actually boots with, and the skel tree must not
# overwrite it — so keep that entry, make it read-only, and append the tmpfs
# mounts reviewed in skel/etc/kiosk/fstab.tmpfs. OpenRC's `root` service only
# remounts / read-write when fstab does not say otherwise, so this is what keeps
# the rootfs read-only for the life of the box.
root_uuid=$(sed -n 's#^UUID=\([^ \t]*\)[ \t]*/[ \t].*#\1#p' /etc/fstab)
root_fs=$(sed -n 's#^UUID=[^ \t]*[ \t]*/[ \t]*\([^ \t]*\).*#\1#p' /etc/fstab)
if [ -z "$root_uuid" ] || [ -z "$root_fs" ]; then
    echo 'setup.sh: no root filesystem entry found in /etc/fstab' >&2
    exit 1
fi
{
    printf '# <fs>\t\t\t<mountpoint>\t<type>\t<options>\t\t<dump/pass>\n'
    printf 'UUID=%s\t/\t\t%s\tro,noatime\t0 1\n' "$root_uuid" "$root_fs"
    cat /etc/kiosk/fstab.tmpfs
} > /etc/fstab

chmod 0755 /etc/init.d/kiosk /usr/local/bin/kiosk-browser
