/**
 * Turns the TUI's BuildOptions into (a) the `alpine-make-vm-image` flag list and
 * (b) the files this build writes that the old hardcoded scripts shipped.
 *
 * Everything here is pure: no sudo, no network, no filesystem — so it is
 * testable and the build step can `--dry-run` it.
 */

import { mkdir, writeFile } from 'node:fs/promises';
import {
  type BuildOptions,
  KANSHI_PACKAGES,
  ORIENTATIONS,
  resolvePackages,
} from './options';

export type BuildInvocation = {
  /** Flat argv for the build tool, in the order build.sh passed them. */
  flags: string[];
  /** Packages joined for a single `--packages` argument. */
  packages: string[];
  /** True when the display options change the shipped files. */
  writesKanshiConfig: boolean;
  /** Human-readable plan lines for the TUI summary and the dry run. */
  summary: { label: string; value: string }[];
};

/**
 * Full build invocation. `imagePath` is positional: the tool formats it in
 * place, which is why build.sh always started from a fresh file.
 */
export async function planBuild(
  options: BuildOptions,
  imagePath: string,
  imageDir: string
): Promise<BuildInvocation> {
  const packages = await resolvePackages(options, imageDir);
  // Display config is applied by kanshi, which is not a default package: add it
  // whenever a non-default orientation, mode or scale is selected.
  for (const pkg of kanshiPackages(options)) {
    if (!packages.includes(pkg)) {
      packages.push(pkg);
    }
  }
  const writesKanshiConfig = kanshiPackages(options).length > 0;

  const flags: string[] = [
    '--arch',
    options.arch,
    '--branch',
    options.branch,
    '--image-format',
    options.imageFormat,
    '--image-size',
    options.imageSize.trim(),
    '--kernel-flavor',
    options.kernelFlavor,
    '--boot-mode',
    options.bootMode,
    '--packages',
    packages.join(' '),
    '--repositories-file',
    'repositories',
    '--fs-skel-dir',
    'skel',
    '--fs-skel-chown',
    'root:root',
    '--script-chroot',
    imagePath,
    'setup.sh',
  ];

  if (options.serialConsole) {
    flags.push('--serial-console');
  }
  if (options.partition) {
    flags.push('--partition');
  }

  // UEFI always gets a GPT with an ESP (alpine-make-vm-image forces it), so the
  // plan must not call a UEFI build "whole-disk" just because the toggle is off.
  let partitions = 'whole-disk (no partition table)';
  if (options.partition) {
    partitions = 'GPT single partition';
  }
  if (options.bootMode === 'UEFI') {
    partitions = 'GPT + ESP (forced by UEFI)';
  }

  const summary = [
    { label: 'Image', value: imagePath },
    { label: 'Boot mode', value: options.bootMode },
    { label: 'Partitions', value: partitions },
    { label: 'Alpine branch', value: options.branch },
    { label: 'Architecture', value: options.arch },
    { label: 'Kernel', value: options.kernelFlavor },
    { label: 'Image size', value: options.imageSize },
    { label: 'Format', value: options.imageFormat },
    {
      label: 'Serial console',
      value: options.serialConsole ? 'on (ttyS0)' : 'off',
    },
    { label: 'Hostname', value: options.hostname },
    { label: 'Timezone', value: options.timezone },
    { label: 'SPA origin', value: options.kioskUrl },
    {
      label: 'Orientation',
      value:
        options.orientation === 'normal'
          ? 'as the TV reports'
          : (ORIENTATION_TEXT[options.orientation] ?? options.orientation),
    },
    {
      label: 'Resolution',
      value:
        options.outputMode === 'none' ? 'output preferred' : options.outputMode,
    },
    { label: 'Scale', value: options.outputScale },
    {
      label: 'Extra packages',
      value:
        options.extraPackages.length > 0
          ? options.extraPackages.join(', ')
          : 'none',
    },
  ];

  return { flags, packages, summary, writesKanshiConfig };
}

const ORIENTATION_TEXT: Record<string, string> = {
  '90': '90° portrait',
  '180': '180°',
  '270': '270° portrait',
  flipped: 'mirrored',
  'flipped-90': 'mirror + 90°',
  'flipped-180': 'mirror + 180°',
  'flipped-270': 'mirror + 270°',
  normal: 'as the TV reports',
};

/**
 * The kanshi config: `output * <transform> [mode] [scale]`, wildcarded because a
 * kiosk box has no console to name its output and the transform belongs on
 * whatever panel it found. kanshi reads this from `-c`, so the file lands under
 * /etc rather than in a home directory that does not exist until after boot.
 */
export function renderKanshiConfig(options: BuildOptions): string {
  const directives = [`    output * transform ${options.orientation}`];
  if (options.outputMode !== 'none') {
    directives.push(`    output * mode ${options.outputMode}`);
  }
  if (options.outputScale !== '1') {
    directives.push(`    output * scale ${options.outputScale}`);
  }
  return `# Generated by apps/kiosk/image/build.ts — do not edit by hand.\nprofile {\n${directives.join('\n')}\n}\n`;
}

/** Packages the image needs when display config is selected. */
export function kanshiPackages(options: BuildOptions): string[] {
  return options.orientation === 'normal' &&
    options.outputMode === 'none' &&
    options.outputScale === '1'
    ? []
    : [...KANSHI_PACKAGES];
}

/** Orientations a TV is likely to use, in picker order. */
export const ORIENTATION_CHOICES = ORIENTATIONS.map(
  (value: (typeof ORIENTATIONS)[number]) => ({
    hint: value === 'normal' ? 'trust the panel' : 'forced transform',
    label: ORIENTATION_TEXT[value] ?? value,
    value,
  })
);

/**
 * The build.env setup.sh reads chrooted inside the image: the tool bind-mounts
 * this directory at /mnt, so a plain KEY=value file is the simplest channel that
 * survives into the chroot.
 */
export function renderBuildEnv(options: BuildOptions): string {
  return [
    '# Generated by apps/kiosk/image/build.ts — read by setup.sh, chrooted.',
    `HOSTNAME=${options.hostname}`,
    `TIMEZONE=${options.timezone}`,
    `KIOSK_URL=${options.kioskUrl}`,
    `ORIENTATION=${options.orientation}`,
    `OUTPUT_MODE=${options.outputMode}`,
    `OUTPUT_SCALE=${options.outputScale}`,
    '',
  ].join('\n');
}

/**
 * Writes the build's generated files, then reports what changed. All of them are
 * build inputs the tool copies into the image: they sit beside the checked-in
 * skel tree, which is why a build leaves them behind and the next one rewrites.
 */
export async function writeGeneratedFiles(
  options: BuildOptions,
  imageDir: string
): Promise<string[]> {
  const written: string[] = [];
  const displaySelected = kanshiPackages(options).length > 0;

  // The channel to setup.sh, bind-mounted at /mnt by --script-chroot.
  await writeFile(`${imageDir}/build.env`, renderBuildEnv(options));
  written.push('build.env');

  // Only when display config was chosen: a kanshi config on a default image
  // would apply a `normal` transform to outputs that already look right.
  if (displaySelected) {
    const kanshiDir = `${imageDir}/skel/etc/kiosk/kanshi`;
    await mkdir(kanshiDir, { recursive: true });
    await writeFile(`${kanshiDir}/config`, renderKanshiConfig(options));
    written.push('skel/etc/kiosk/kanshi/config');

    // Alpine's kanshi package ships no init script, so the service is generated
    // here rather than enabled by name. It runs as the kiosk user because the
    // output-management protocol needs the same seat cage takes.
    const initDir = `${imageDir}/skel/etc/init.d`;
    await writeFile(`${initDir}/kanshi`, renderKanshiInit());
    written.push('skel/etc/init.d/kanshi');
  }
  return written;
}

/** OpenRC service that applies the generated kanshi config before cage starts. */
function renderKanshiInit(): string {
  return `#!/sbin/openrc-run
# Generated by apps/kiosk/image/build.ts — applies the display transform chosen
# in the TUI. Alpine ships no kanshi service, so this is the whole unit.
name="kanshi"
description="Applies the kiosk display configuration"

supervisor="supervise-daemon"
command="/usr/bin/kanshi"
command_args="-c /etc/kiosk/kanshi/config"
command_user="kiosk:kiosk"
output_log="/var/log/kanshi.log"
error_log="/var/log/kanshi.log"
respawn_delay=5

depend() {
    need seatd
    before kiosk
    use net
}

start_pre() {
    install -d -m 0700 -o kiosk -g kiosk /run/kiosk
    export XDG_RUNTIME_DIR=/run/kiosk
}
`;
}
